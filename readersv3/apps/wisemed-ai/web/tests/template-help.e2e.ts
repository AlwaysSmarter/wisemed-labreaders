import {expect,test} from '@playwright/test'

for(const width of [1440,390])test(`contextual template help preserves the draft at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:900})
  const template={id:'11111111-1111-4111-8111-111111111111',version_id:'22222222-2222-4222-8222-222222222222',version:1,owner_id:'doctor',name:'Ecografie de test',specialty:'Cardiologie',specialties:['Cardiologie'],html:'<section data-section="ficat"><p>{{siv}}</p></section>',fields:[{key:'siv',label:'Sept interventricular',type:'number',unit:'mm',aliases:['SIV'],section:'ficat'}],sections:[{id:'ficat',label:'Ficat',parent:'',variants:[{id:'normal',label:'Aspect normal',detail:'standard',condition_field:'siv',condition_value:'normal',text:'Descriere {{siv}}'}]}],rules:[],fragments:{},semantic_mapping:{}}
  const writes:string[]=[]
  await page.route('**/v1/**',route=>{
    const path=new URL(route.request().url()).pathname
    if(route.request().method()!=='GET')writes.push(path)
    const responses:Record<string,unknown>={
      '/v1/auth/providers':{standalone:true},
      '/v1/profile':{name:'Admin Test',role:'admin',instance_admin:true},
      '/v1/billing/account':{},'/v1/dashboard':{},'/v1/templates':[template],
      [`/v1/templates/${template.id}/speech-adaptation`]:{vocabulary_version:1,sections:[]}
    }
    return route.fulfill({json:responses[path]??[]})
  })
  await page.goto('/ai/#/templates')
  const toggle=page.getByRole('button',{name:'Ajutor contextual',exact:true})
  await expect(toggle).toHaveAttribute('aria-pressed','false')
  await expect(page.locator('.help-hint')).toHaveCount(0)
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed','true')
  await page.getByRole('button',{name:'Ajutor: Biblioteca de șabloane',exact:true}).click()
  const dialog=page.getByRole('dialog')
  await expect(dialog).toContainText('rezultatele filtrate')
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await page.getByRole('button',{name:'Editează',exact:true}).click()
  await page.getByRole('button',{name:'Sept interventricular',exact:true}).click()
  const aliases=page.locator('label').filter({has:page.getByRole('button',{name:'Ajutor: Aliasuri',exact:true})}).locator('input')
  await expect(aliases).toHaveValue('SIV')
  await expect(page.getByLabel('Aliasuri (virgulă)',{exact:true})).toHaveValue('SIV')
  await page.getByRole('button',{name:'Ajutor: Aliasuri',exact:true}).focus()
  await page.keyboard.press('Enter')
  await expect(dialog).toContainText('SIV, sept interventricular')
  await expect(dialog).toBeVisible()
  await page.getByRole('button',{name:'Am înțeles',exact:true}).click()
  await expect(aliases).toHaveValue('SIV')
  await expect(page.getByRole('button',{name:'Ajutor: Aliasuri',exact:true})).toBeFocused()
  const required=page.locator('label.check').filter({has:page.getByRole('button',{name:'Ajutor: Obligatoriu',exact:true})}).locator('input')
  await expect(required).not.toBeChecked()
  await page.getByRole('button',{name:'Ajutor: Obligatoriu',exact:true}).click()
  await page.keyboard.press('Escape')
  await expect(required).not.toBeChecked()
  await page.getByRole('button',{name:'Ajutor: Context AI al șablonului',exact:true}).click()
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('details').filter({has:page.locator('summary > .help-hint[aria-label="Ajutor: Context AI al șablonului"]')})).not.toHaveAttribute('open')
  await page.getByRole('button',{name:'Ajutor: Fragmente normal/patologic',exact:true}).first().click()
  await expect(dialog).toContainText('Exemplu de fragment normal')
  await expect(dialog).toContainText('ficat_descriere')
  await expect(dialog).toContainText('variantele de redactare')
  await page.keyboard.press('Escape')
  await page.locator('.section-card > summary').click()
  await page.getByRole('button',{name:'Ajutor: În cadrul secțiunii',exact:true}).click()
  await expect(dialog).toContainText('secțiunea părinte')
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'Ajutor: Nivel de detaliu implicit',exact:true}).first().click()
  for(const option of ['Scurt (brief)','Standard (standard)','Detaliat (detailed)','Din șablon'])await expect(dialog).toContainText(option)
  await page.keyboard.press('Escape')
  await page.locator('.variant-card > summary').click()
  await page.getByRole('button',{name:'Ajutor: Regulă de aplicare',exact:true}).click()
  await expect(dialog).toContainText('Valoare exactă')
  await expect(dialog).toContainText('Câmp documentat explicit')
  await page.keyboard.press('Escape')
  await expect(page.locator('.variant-card')).toHaveAttribute('open','')
  await expect(dialog).toHaveCount(0)
  await page.screenshot({path:`/tmp/wisemed-template-help-${width}.png`,fullPage:true})
  await toggle.click()
  await expect(page.locator('.help-hint')).toHaveCount(0)
  await expect(page.getByLabel('Aliasuri (virgulă)',{exact:true})).toHaveValue('SIV')
  expect(writes).toEqual([])
})
