import {test,expect} from '@playwright/test'
import {readFileSync} from 'node:fs'
import {resolve} from 'node:path'
test('overdue subscriber can view debt, verified payment restores work',async({page,browser})=>{
 test.skip(!process.env.WAI_SYNTHETIC_BILLING_USER,'Requires the disposable PostgreSQL browser fixture')
 const email=process.env.WAI_SYNTHETIC_BILLING_USER!
 await page.goto('/ai/')
 await page.getByLabel('Email',{exact:true}).fill(email)
 await page.getByLabel('Parolă',{exact:true}).fill('synthetic-password-123')
 await page.getByRole('button',{name:'Autentificare',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Pachetul meu',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Sesiune clinică',exact:true})).toHaveCount(0)
 await expect(page.getByText('Accesul de lucru este suspendat.',{exact:false})).toBeVisible()
 await expect(page.locator('.p-message-enter-active')).toHaveCount(0)
 await page.screenshot({path:'test-results/subscription-suspended.png',fullPage:true,animations:'disabled'})
 const adminContext=await browser.newContext()
 const admin=await adminContext.newPage()
 await admin.goto((process.env.WAI_BASE_URL||'http://127.0.0.1:19120')+'/ai/')
 await admin.getByLabel('Email',{exact:true}).fill('admin@wisemed.local')
 await admin.getByLabel('Parolă',{exact:true}).fill(readFileSync(process.env.WAI_PASSWORD_FILE||resolve('../../../output/wisemed-ai/deployments/ai-bootstrap-password'),'utf8').trim())
 await admin.getByRole('button',{name:'Autentificare',exact:true}).click()
 await admin.getByRole('button',{name:'Pachete și monetizare',exact:true}).click()
 await admin.getByLabel('Caută utilizator',{exact:true}).fill(email)
 await admin.getByRole('button',{name:'Gestionează',exact:true}).click()
 await admin.getByRole('button',{name:'Înregistrează plata verificată',exact:true}).click()
 await admin.getByLabel('Referința unică a plății efectiv primite',{exact:true}).fill('synthetic-browser-payment')
 await admin.getByLabel('Confirm că plata a fost primită și verificată.',{exact:true}).check()
 await admin.getByRole('button',{name:'Confirmă înregistrarea plății',exact:true}).click()
 await expect(admin.getByText('Abonamentul este activ.',{exact:false})).toBeVisible()
 await page.reload()
 await expect(page.getByRole('heading',{name:'Privire de ansamblu',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Sesiune clinică',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Pachetul meu',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Statistici pe șablon și operație',exact:true})).toBeVisible()
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await adminContext.close()
})
