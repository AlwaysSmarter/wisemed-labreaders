import {expect,test} from '@playwright/test'

for(const width of [1440,390])test(`WYSIWYG formatting, tables and publication at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:900})
  const template={id:'11111111-1111-4111-8111-111111111111',version_id:'22222222-2222-4222-8222-222222222222',version:1,name:'Raport de test',specialty:'Cardiologie',specialties:['Cardiologie'],html:'<section data-section="ficat"><h2>Raport</h2><p>Ficat: <span data-field="ficat">Aspect ficat</span></p></section><p>Text editabil</p>',fields:[{key:'ficat',label:'Aspect ficat',type:'string',section:'ficat'}],sections:[{id:'ficat',label:'Ficat',parent:''}],rules:[],fragments:{},semantic_mapping:{}}
  let published:any
  await page.route('**/v1/**',route=>{
    const path=new URL(route.request().url()).pathname
    if(path==='/v1/templates'&&route.request().method()==='POST'){
      published=route.request().postDataJSON()
      return route.fulfill({json:{...published,version:2}})
    }
    const responses:Record<string,unknown>={'/v1/auth/providers':{standalone:true},'/v1/profile':{name:'Admin',role:'admin',instance_admin:true},'/v1/billing/account':{},'/v1/dashboard':{},'/v1/templates':[template]}
    return route.fulfill({json:responses[path]??[]})
  })
  await page.goto('/ai/#/templates')
  await page.getByRole('button',{name:'Editează',exact:true}).click()
  const editor=page.getByRole('textbox',{name:'Conținutul șablonului',exact:true})
  const button=(name:string)=>page.getByRole('button',{name,exact:true})
  await expect(page.getByText('Text editabil · WYSIWYG')).toBeVisible()
  await button('Fragment normal').click()
  await expect(page.getByText(/Fragmentul „normal” nu este definit/)).toBeVisible()
  await button('Scrie în document').click()
  await expect(editor).toBeFocused()
  await editor.press('ControlOrMeta+End')
  await editor.press('Enter')
  await expect(button('Aldin')).toHaveText('B')
  await button('Aldin').click()
  await expect(button('Aldin')).toHaveAttribute('aria-pressed','true')
  await button('Subliniat').click()
  await button('Tăiat').click()
  await page.keyboard.type('Text formatat')
  for(const tag of ['strong','u','s'])await expect(editor.locator(tag)).toHaveText('Text formatat')
  await button('Centrează').click()
  await expect(editor.locator('p[style*="text-align: center"]')).toContainText('Text formatat')
  await button('Anulează').click()
  await expect(editor.locator('p[style*="text-align: center"]')).toHaveCount(0)
  await button('Refă').click()
  await expect(editor.locator('p[style*="text-align: center"]')).toHaveCount(1)
  await page.getByLabel('Stil de paragraf').selectOption('3')
  await expect(editor.locator('h3')).toContainText('Text formatat')
  await editor.press('ControlOrMeta+End')
  await editor.press('Enter')
  await page.getByLabel('Stil de paragraf').selectOption('paragraph')
  await button('Inserează tabel').click()
  await expect(editor.locator('table tr')).toHaveCount(3)
  await expect(page.getByRole('toolbar',{name:'Editarea tabelului',exact:true})).toBeVisible()
  await page.keyboard.type('Celulă de test')
  await button('Rând dedesubt').click()
  await expect(editor.locator('table tr')).toHaveCount(4)
  await button('Coloană la dreapta').click()
  await expect(editor.locator('table tr').first().locator('th,td')).toHaveCount(4)
  await button('Editează sursa HTML').click()
  const source=page.getByRole('textbox',{name:'Sursă HTML',exact:true})
  await expect(source).toHaveValue(/data-section="ficat"/)
  await expect(source).toHaveValue(/data-field="ficat"/)
  await expect(source).toHaveValue(/text-align: center/)
  await expect(button('Aldin')).toBeDisabled()
  await source.fill((await source.inputValue()).replace('Text editabil','Text modificat din HTML'))
  await button('Revino la editorul vizual').click()
  await expect(editor).toContainText('Text modificat din HTML')
  await expect(editor.locator('table tr')).toHaveCount(4)
  await page.locator('summary').filter({hasText:'Reguli, secțiuni și fragmente'}).click()
  await page.getByLabel('Fragmente normal/patologic',{exact:true}).fill(JSON.stringify({normal:'<p>Fragment de probă</p>',patologic:'<p>Constatare: {{ficat}}</p>'}))
  await editor.press('ControlOrMeta+End')
  await button('Fragment normal').click()
  await expect(editor).toContainText('Fragment de probă')
  await page.locator('.section-card > summary').click()
  await page.getByRole('textbox',{name:'Dicționar: Ficat',exact:true}).fill('ecostructură\naspect fin granular')
  await button('Publică versiune').click()
  await expect.poll(()=>published?.html).toContain('Text modificat din HTML')
  expect(published.html).toContain('text-align: center')
  expect(published.sections[0].speech_terms).toEqual(['ecostructură','aspect fin granular'])
  expect(published.html).toContain('<u>')
  expect(published.html).toContain('<s>')
  expect(published.html).toContain('data-section="ficat"')
  expect(published.html).toContain('data-field="ficat"')
  await expect(editor).toContainText('Text formatat')
  await page.screenshot({path:`/tmp/wisemed-wysiwyg-${width}.png`,fullPage:true})
})
