import {test,expect} from '@playwright/test'
import {readFileSync} from 'node:fs'
import {resolve} from 'node:path'
test('clinical workflow, template editor, admin and mobile layout',async({page})=>{
 const password=readFileSync(process.env.WAI_PASSWORD_FILE||resolve('../../../output/wisemed-ai/deployments/ai-bootstrap-password'),'utf8').trim()
 await page.goto('/ai/')
 await expect(page.getByRole('heading',{name:'Autentificare'})).toBeVisible()
 await page.getByLabel('Email',{exact:true}).fill('admin@wisemed.local')
 await page.getByLabel('Parolă',{exact:true}).fill(password)
 await page.getByRole('button',{name:'Autentificare'}).click()
 await expect(page.getByRole('heading',{name:'Privire de ansamblu',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Șabloane',exact:true}).click()
 await page.getByLabel('Caută după specialitate sau șablon',{exact:true}).fill('neurologie')
 await page.getByRole('button',{name:'Editează',exact:true}).first().click()
 await expect(page.getByRole('heading',{name:'Editor de șablon',exact:true})).toBeVisible()
 expect(await page.locator('.tiptap section[data-section] section[data-section]').count()).toBeGreaterThan(0)
 await page.getByText('Context AI al șablonului · memorie persistentă',{exact:true}).click()
 await page.getByLabel('Reguli de completare',{exact:true}).fill('Exemplu sintetic: păstrează negațiile și citează sursa.')
 await expect(page.getByLabel('Terminologie și abrevieri',{exact:true})).toBeVisible()
 await page.getByText('Propune câmpuri dintr-un raport existent',{exact:true}).click()
 await page.getByLabel('Raport de referință',{exact:true}).fill('Câmp sintetic: observație sintetică')
 await page.getByRole('button',{name:'Propune câmpuri',exact:true}).click()
 await expect(page.getByRole('button',{name:'Acceptă propunerile în editor',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Acceptă propunerile în editor',exact:true}).click()
 await page.getByRole('button',{name:'Adaugă un câmp',exact:true}).click()
 await expect(page.getByLabel('Identificator',{exact:true})).toBeVisible()
 await page.getByLabel('Etichetă',{exact:true}).fill('Câmp sintetic test')
 await expect(page.locator('.tiptap')).toContainText('Câmp sintetic test')
 await page.getByRole('button',{name:'Sesiune clinică',exact:true}).click()
 await page.getByRole('combobox').click()
 await page.getByRole('option',{name:'Ecografie abdominală',exact:true}).click()
 await page.getByLabel('Referință pacient',{exact:true}).fill('DEMO-E2E-SYNTHETIC')
 await page.getByRole('button',{name:'Deschide sesiune',exact:true}).click()
 await expect(page.locator('.session-banner')).toBeVisible()
 await page.getByRole('button',{name:'Exemplu sintetic',exact:true}).click()
 await expect(page.locator('.report')).toContainText('ecostructură omogenă')
 await page.getByText('Stilul raportului · nivel de detaliu pe secțiuni',{exact:true}).click()
 await page.getByLabel('Nivelul întregului raport',{exact:true}).click()
 await page.getByRole('option',{name:'Scurt',exact:true}).click()
 await expect(page.getByRole('listbox')).toHaveCount(0)
 await page.getByLabel('↳ Ficat',{exact:true}).click()
 await page.getByRole('option',{name:'Detaliat',exact:true}).click()
 await page.getByRole('button',{name:'Aplică stilul raportului',exact:true}).click()
 await expect(page.locator('.report')).toContainText('140')
 await page.getByRole('button',{name:'Finalizează pentru revizuire',exact:true}).click()
 await expect(page.getByRole('button',{name:'Aprobă rezultatul',exact:true})).toBeDisabled()
 await page.getByLabel(/Confirm revizuirea datelor clinice/).check()
 await page.getByRole('button',{name:'Aprobă rezultatul',exact:true}).click()
 await expect(page.getByRole('button',{name:'Export JSON',exact:true})).toBeVisible()
 await page.screenshot({path:'test-results/clinical-desktop.png',fullPage:true})
 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:'test-results/clinical-mobile.png',fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.getByRole('button',{name:'Șterge sesiunea',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Pregătiți spațiul de consultație'})).toBeVisible()
 await page.setViewportSize({width:1440,height:1000})
 await page.getByRole('button',{name:'Configurare',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Provider AI și buget',exact:true})).toBeVisible()
 await expect(page.getByText('AES-256-GCM',{exact:true})).toBeVisible()
 await expect(page.getByRole('heading',{name:'Configurare completă a utilitarului',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Verifică actualizările acum',exact:true}).click()
 await expect(page.locator('pre').filter({hasText:'not_configured'})).toBeVisible()
 await page.getByRole('button',{name:'Audit',exact:true}).click()
 await expect(page.locator('table')).toContainText('result.approve')
})
